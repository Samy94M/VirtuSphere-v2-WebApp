<?php

declare(strict_types=1);

use PHPUnit\Framework\TestCase;

require_once dirname(__DIR__, 2) . '/lib/audit_presenter.php';

/**
 * Golden net for audit_event_description(). Every English sentence the writer
 * stores is pinned byte for byte, so the presenter can be rebuilt as a catalog
 * renderer without changing one stored line (search, CSV export and the E2E
 * assertions match these words).
 *
 * The golden file is generated from the same cases by
 * tests/tools/audit-presenter-golden.php; regenerate it after any case change.
 */
final class AuditPresenterGoldenTest extends TestCase
{
    /** @return list<array{id:string,event:string,object_type:string,object_id:?string,result:string,context:array<string,mixed>}> */
    private function cases(): array
    {
        $cases = require dirname(__DIR__) . '/fixtures/audit_presenter_cases.php';
        self::assertIsArray($cases);
        self::assertNotEmpty($cases, 'zero-match: the case fixture must hold cases');

        return $cases;
    }

    /** @return array<string,string> */
    private function golden(): array
    {
        $path = dirname(__DIR__) . '/fixtures/audit_presenter_golden.json';
        self::assertFileExists($path, 'the golden file is generated by tests/tools/audit-presenter-golden.php');
        $decoded = json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);
        self::assertIsArray($decoded);

        return $decoded;
    }

    public function testEveryCaseRendersItsGoldenSentence(): void
    {
        $golden = $this->golden();
        foreach ($this->cases() as $case) {
            self::assertArrayHasKey($case['id'], $golden, $case['id'] . ' has no golden sentence; regenerate the golden file');
            self::assertSame(
                $golden[$case['id']],
                audit_event_description($case['event'], $case['object_type'], $case['object_id'], $case['result'], $case['context']),
                $case['id']
            );
        }
    }

    public function testEveryEventArmOfThePresenterHasACase(): void
    {
        $source = (string) file_get_contents(dirname(__DIR__, 2) . '/lib/audit_presenter.php');
        preg_match_all('/^\s*(VIRTUSPHERE_AUDIT_EVENT_[A-Z0-9_]+)\s*=>/m', $source, $matches);
        $arms = array_values(array_unique($matches[1]));
        self::assertNotEmpty($arms, 'zero-match: the presenter source names no event arm');

        $covered = array_unique(array_column($this->cases(), 'event'));
        foreach ($arms as $arm) {
            self::assertTrue(defined($arm), $arm . ' is named in the presenter but is not defined');
            self::assertContains(constant($arm), $covered, $arm . ' has no golden case');
        }
    }

    public function testCaseIdsAreUniqueSnakeCase(): void
    {
        $ids = array_column($this->cases(), 'id');
        $duplicates = array_keys(array_filter(array_count_values($ids), static fn (int $count): bool => $count > 1));
        self::assertSame([], $duplicates, 'duplicate case ids');
        foreach ($ids as $id) {
            self::assertMatchesRegularExpression('/^[a-z][a-z0-9_]*$/', $id);
        }
    }

    public function testTheGoldenFileHoldsExactlyTheCaseIds(): void
    {
        $ids = array_map('strval', array_column($this->cases(), 'id'));
        $keys = array_map('strval', array_keys($this->golden()));
        sort($ids, SORT_STRING);
        sort($keys, SORT_STRING);
        self::assertSame($ids, $keys, 'the golden file and the cases disagree; regenerate the golden file');
    }

    public function testEveryCaseIsARowTheWriterWouldStore(): void
    {
        foreach ($this->cases() as $case) {
            $definition = audit_event_definition($case['event'], $case['object_type'], $case['object_id'], $case['result']);

            $expected = $case['context'];
            ksort($expected);
            self::assertSame(
                $expected,
                audit_context_normalize($case['context'], $definition, $case['result']),
                $case['id'] . ': the context is not what audit_context_normalize() leaves'
            );
            self::assertSame(
                $case['object_id'],
                audit_object_id($case['object_id'], audit_event_object_id_kind($case['event'])),
                $case['id'] . ': the object id is not what audit_object_id() leaves'
            );
        }
    }

    public function testAnUnregisteredEventCodeIsRefusedNotRendered(): void
    {
        // The match has a default arm that throws; the golden cases can never reach it.
        $this->expectException(LogicException::class);
        audit_event_description('auth.not_an_event', 'user', '1', VIRTUSPHERE_AUDIT_RESULT_SUCCESS, []);
    }
}
